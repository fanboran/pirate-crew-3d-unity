    /// 表未覆盖时回退 RecalculateNormals 近似（G-plants.md §2.1：shader 只把 q·normal
    /// 用于 NdotL 假光照）。已入库的凸包资产用菜单 Bake 重烘一次即吃到法线（幂等覆盖）。
    ///
    /// 【资产落点】Assets/Art/WaterLabReplica/PlantHulls/（复刻真值资产聚集目录，
    /// 与快照 .bytes 同区；不在 MaterialFolder——装配对材质目录是先删后建）。
    /// 菜单：Tools/PirateCrew/WaterLab/Bake Plant Hull Meshes。
    /// </summary>
    public static class WaterLabPlantBake
    {
        public const string HullFolder = "Assets/Art/WaterLabReplica/PlantHulls";

        internal struct HullData
        {
            public string Name;
            public float[] Positions;   // xyz 打平（positions_all 逐字）
            public int[] Indices;       // 三角索引（mesh_full.indices 逐字）
            public Vector3 AabbCenter;  // 原作 localAABB.m_Center
            public Vector3 AabbExtent;  // 原作 localAABB.m_Extent
        }

        [MenuItem("Tools/PirateCrew/WaterLab/Bake Plant Hull Meshes")]
        public static void BakeFromMenu()
        {
            var meshes = EnsureHullMeshes();
            int baked = 0;
            foreach (var m in meshes)
                if (m != null) baked++;
            Debug.Log($"[WaterLabPlantBake] 植物凸包网格就绪：{baked}/{meshes.Length}（{HullFolder}）");
        }

        /// <summary>装配期入口（WaterLabSetup.EnsurePlants）：返回与
        /// <see cref="PirateCrew.WaterLab.ReplicaPlantTable.All"/> 同序的 Mesh 数组。
        /// 资产已存在则加载（幂等）；缺失则从内嵌真值数据构建并存盘。</summary>
        public static Mesh[] EnsureHullMeshes()
        {
            EnsureFolder(HullFolder);
            var result = new Mesh[Hulls.Length];
            for (int i = 0; i < Hulls.Length; i++)
            {
                var d = Hulls[i];
                string path = $"{HullFolder}/{d.Name}.asset";
                var mesh = AssetDatabase.LoadAssetAtPath<Mesh>(path);
                if (mesh == null)
                {
                    mesh = BuildMesh(d);
                    AssetDatabase.CreateAsset(mesh, path);
                }
                result[i] = mesh;
            }
            AssetDatabase.SaveAssets();
            return result;
        }

        static Mesh BuildMesh(HullData d)
        {
            int count = d.Positions.Length / 3;
            var vertices = new Vector3[count];
            for (int i = 0; i < count; i++)
                vertices[i] = new Vector3(d.Positions[i * 3], d.Positions[i * 3 + 1], d.Positions[i * 3 + 2]);
            var mesh = new Mesh { name = d.Name };
            mesh.vertices = vertices;
            mesh.triangles = d.Indices; // 全部 < 65536 顶点，16bit 索引足够
            if (!PirateCrew.WaterLab.WaterLabHullNormals.Apply(d.Name, mesh))
                mesh.RecalculateNormals();  // 表未覆盖时回退近似（当前 13/13 全覆盖，F3 §6）
            // 原作 localAABB 直灌：几何元数据与原作一致（实例级剔除走系统的
            // DrawBounds=Beach.bounds，本 bounds 只承载 mesh 自身元数据）。
            mesh.bounds = new Bounds(d.AabbCenter, d.AabbExtent * 2f);
            return mesh;
        }

        static void EnsureFolder(string folder)
        {
            var parts = folder.Split('/');
            string current = "Assets";
            for (int i = 1; i < parts.Length; i++)
            {
                string next = current + "/" + parts[i];
                if (!AssetDatabase.IsValidFolder(next))
                    AssetDatabase.CreateFolder(current, parts[i]);
                current = next;
            }
        }

